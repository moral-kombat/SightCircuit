"""Build and place the fake ``vrclient.so`` of ``tests/fixtures/fake_vrclient.cpp`` for the overlay bridge's tests.

The bridge links the SDK's public loader, which finds its runtime through the
path registry named by ``VR_PATHREG_OVERRIDE`` and loads
``<runtime>/bin/<platform>/vrclient.so`` from it. ``runtime(directory)``
compiles the fake against the pinned SDK headers the bridge was built with,
lays out such a runtime under ``directory`` and returns the environment
additions and the call log's path. Nothing here is a device or a display: the
fake records the bridge's calls with their times, and can delay or fail them.
"""
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SDK = ROOT / ".cache/openvr"
SOURCE = ROOT / "tests/fixtures/fake_vrclient.cpp"
PLATFORM_DIRECTORY = {"x86_64": "linux64", "aarch64": "linuxarm64", "arm64": "linuxarm64"}


def available():
    return (os.name == "posix" and shutil.which("g++") is not None and (SDK / "headers/openvr.h").is_file()
            and platform.machine() in PLATFORM_DIRECTORY)


def stubs_text(header):
    """A default body for every pure virtual of ``IVRSystem`` and ``IVROverlay`` in the SDK header."""
    lines = ["// Generated by tests/fake_vrclient.py from openvr.h; not committed.", "#pragma once",
             "#include <openvr.h>", "using namespace vr;"]
    for name in ("IVRSystem", "IVROverlay"):
        body = re.search(r"class %s\s*\{(.*?)\n\t?\};" % name, header, re.S).group(1)
        body = re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", body), flags=re.S)
        lines.append(f"struct Fake{name[3:]}Stubs : vr::{name} {{")
        for declaration in re.findall(r"virtual\s+(.*?)\s*=\s*0\s*;", body, re.S):
            declaration = " ".join(declaration.split())
            returns_nothing = re.match(r"void\s+\w+\s*\(", declaration) is not None
            lines.append(f"    {declaration} override {{{'' if returns_nothing else ' return {}; '}}}")
        lines.append("};")
    return "\n".join(lines) + "\n"


def runtime(directory):
    """Build the fake under ``directory``; returns ``(environment additions, call log path)``."""
    directory = Path(directory)
    build = directory / "build"
    binaries = directory / "runtime/bin" / PLATFORM_DIRECTORY[platform.machine()]
    for path in (build, binaries, directory / "config", directory / "log"):
        path.mkdir(parents=True, exist_ok=True)
    (build / "fake_vrclient_stubs.hpp").write_text(stubs_text((SDK / "headers/openvr.h").read_text()))
    subprocess.run(["g++", "-std=c++17", "-O1", "-shared", "-fPIC", "-Wall", "-Werror", "-Wno-unused-parameter",
                    f"-I{SDK / 'headers'}", f"-I{SDK / 'src'}", f"-I{build}", str(SOURCE),
                    "-o", str(binaries / "vrclient.so")], check=True, capture_output=True, timeout=120)
    registry = directory / "openvrpaths.vrpath"
    registry.write_text(json.dumps({"runtime": [str(directory / "runtime")], "config": [str(directory / "config")],
                                    "log": [str(directory / "log")], "external_drivers": None,
                                    "jsonid": "vrpathreg", "version": 1}))
    log = directory / "calls.jsonl"
    return {"VR_PATHREG_OVERRIDE": str(registry), "FAKE_VR_LOG": str(log)}, log


def calls(log):
    """The fake's logged calls, in order."""
    return [json.loads(line) for line in Path(log).read_text().splitlines()] if Path(log).is_file() else []
