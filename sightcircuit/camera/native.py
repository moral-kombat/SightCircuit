"""Generated native copy of camera export v1: ``tools/camera_export_protocol.hpp``.

The helper's ``--export-frames`` mode includes the header instead of repeating
Python values: the packet prefix layout, the size bounds, the header kinds,
the end reasons, the pixel paths and derivations, the format vocabulary, the
run limits and the exact field list of each header kind (as comma-separated
strings the helper's tests can compare against what it writes).
``scripts/camera_contract_header.py`` writes or checks it; ``kContractDigest``
pins every generated value. The renderer is ``sightcircuit.native_header``,
shared with the HUD contract.
"""
from pathlib import Path
import struct

from .. import native_header
from . import contract

HEADER = Path(__file__).resolve().parents[2] / "tools/camera_export_protocol.hpp"
NAMESPACE = "sightcircuit_camera_export"
BANNER = ("// Generated by scripts/camera_contract_header.py from sightcircuit/camera/contract.py.\n"
          "// Do not edit: change the Python value, then run\n"
          "// python3 scripts/camera_contract_header.py --write and rebuild the camera helper.\n")
UNSUPPORTED, DUPLICATED = "camera_contract_value_unsupported", "camera_contract_name_duplicated"
UINT32, UINT64 = native_header.UINT32, native_header.UINT64


def _names(prefix, values):
    """``kPrefixValue`` constants for a vocabulary tuple, one per value, in contract order."""
    return [(f"k{prefix}{native_header.camel(value.replace('.', '_'))}", "char[]", value) for value in values]


def _layout(prefix, layout):
    """Byte offset of each little-endian prefix field, then the prefix size."""
    entries, codes = [], "<"
    for name, code in layout:
        entries.append((f"k{prefix}{native_header.camel(name)}Offset", UINT32, struct.calcsize(codes)))
        codes += code
    return entries + [(f"k{prefix}Bytes", UINT32, struct.calcsize(codes))]


def _bounds(limits):
    """``kMinFps``/``kMaxFps`` for ``fps``, ``kMinSeconds``/``kMaxSeconds`` for ``max_seconds``, and so on."""
    entries = []
    for name, (low, high) in limits.items():
        stem = native_header.camel(name.removeprefix("max_"))
        entries += [(f"kMin{stem}", UINT32, low), (f"kMax{stem}", UINT32, high)]
    return entries


def _sections():
    if struct.calcsize("<" + dict(contract.PREFIX_FIELDS)["magic"]) != len(contract.MAGIC):
        raise ValueError("camera_contract_magic_size")
    if struct.calcsize(contract.PREFIX_FORMAT) != contract.PREFIX_BYTES:
        raise ValueError("camera_contract_prefix_size")
    return (
        ("Packet prefix: sightcircuit.camera.contract PREFIX_FIELDS, little-endian",
         [("kProtocol", "char[]", contract.PROTOCOL), ("kMagic", "char[]", contract.MAGIC.decode("ascii")),
          ("kVersion", UINT32, contract.VERSION)] + _layout("Prefix", contract.PREFIX_FIELDS) +
         [("kMaxHeaderBytes", UINT32, contract.MAX_HEADER_BYTES),
          ("kMaxPayloadBytes", UINT32, contract.MAX_PAYLOAD_BYTES)]),
        ("Header kinds and their exact fields, in order", _names("Kind", contract.KINDS) +
         [(f"k{native_header.camel(kind)}Fields", "char[]", ",".join(contract.field_names(kind)))
          for kind in contract.KINDS] +
         [("kAcquisitionFormatFields", "char[]", ",".join(field.name for field in contract.ACQUISITION_FORMAT_FIELDS)),
          ("kPlaneFields", "char[]", ",".join(field.name for field in contract.PLANE_FIELDS)),
          ("kLimitFields", "char[]", ",".join(field.name for field in contract.LIMIT_FIELDS)),
          ("kCountFields", "char[]", ",".join(field.name for field in contract.COUNT_FIELDS)),
          ("kStreamRules", "char[]", ",".join(contract.STREAM_RULES))]),
        ("Vocabulary: backends, pixel paths and their derivations, end reasons",
         _names("Backend", contract.BACKENDS) + _names("PixelPath", contract.PIXEL_PATHS) +
         _names("Derivation", tuple(contract.DERIVATIONS.values())) +
         [(f"kDerivationOf{native_header.camel(path)}", "char[]", derivation)
          for path, derivation in contract.DERIVATIONS.items()] +
         _names("EndReason", contract.END_REASONS) +
         [("kBoundedEndReasons", "char[]", ",".join(contract.BOUNDED_END_REASONS))] +
         _names("Confirmation", contract.CONFIRMATIONS) +
         [("kParentConfirmedFlag", "char[]", contract.PARENT_CONFIRMED_FLAG),
          ("kExportNotice", "char[]", contract.EXPORT_NOTICE)]),
        ("Frames: delivered format, bounds, cameras",
         [("kFourcc", "char[]", contract.FOURCC), ("kMaxSide", UINT32, contract.MAX_SIDE),
          ("kMaxPlanes", UINT32, contract.MAX_PLANES), ("kCameraCount", UINT32, len(contract.CAMERA_INDICES)),
          ("kCameraIndices", UINT32 + "[]", contract.CAMERA_INDICES)] +
         [(f"kSourceId{name}", "char[]", value)
          for name, value in zip(("Left", "Right"), contract.SOURCE_IDS)]),
        ("Acquisition format vocabulary: the helper's spelling of the SDK enumerators",
         _names("PixelFormat", contract.PIXEL_FORMATS) + _names("Encoding", contract.ENCODINGS) +
         _names("Transfer", contract.TRANSFERS) + _names("Primaries", contract.PRIMARIES) +
         [("kHexU32Pattern", "char[]", contract.HEX_U32), ("kHexU64Pattern", "char[]", contract.HEX_U64),
          ("kSha256HexPattern", "char[]", contract.SHA256_HEX)]),
        ("Run limits: sightcircuit.camera.contract.LIMITS, echoed in ready", _bounds(contract.LIMITS)),
    )


def contract_digest():
    """SHA-256 of every generated name, type and value."""
    return native_header.digest_of(native_header.entries_of(_sections(), DUPLICATED))


def header_text():
    return native_header.render(BANNER, NAMESPACE, _sections(),
                                "SHA-256 of every value above; the helper may report it in ready.build.",
                                unsupported=UNSUPPORTED, duplicated=DUPLICATED)


def check(path=HEADER):
    """True when ``path`` holds exactly the generated header."""
    return native_header.check(path, header_text())


def write(path=HEADER):
    """Replace ``path`` with the generated header; returns whether it changed."""
    return native_header.write(path, header_text())
