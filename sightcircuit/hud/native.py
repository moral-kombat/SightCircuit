"""Generated native copy of the HUD contract: ``tools/hud_contract.hpp``.

The bridge's units (through ``tools/overlay_bridge.hpp``) and
``tools/overlay_frame.hpp`` include the header instead of repeating Python
values: ``HudConfig``, the calibration marker, the packet layout and opcodes,
the panel limits and defaults, the marker duration, display age and frame-size
limits, and the bridge's connect budget. ``scripts/hud_contract_header.py``
writes or checks it. ``kContractDigest`` pins every generated value, so a built
bridge can report which contract it was compiled from.
"""
from dataclasses import fields
from pathlib import Path
import struct

from .. import native_header, overlay
from . import contract

HEADER = Path(__file__).resolve().parents[2] / "tools/hud_contract.hpp"
NAMESPACE = "sightcircuit_contract"
BANNER = ("// Generated by scripts/hud_contract_header.py from sightcircuit/hud/contract.py\n"
          "// and sightcircuit/overlay.py. Do not edit: change the Python value, then run\n"
          "// python3 scripts/hud_contract_header.py --write and rebuild the bridge.\n")
UINT32 = native_header.UINT32
UNSUPPORTED, DUPLICATED = "hud_contract_value_unsupported", "hud_contract_name_duplicated"
_camel = native_header.camel


def _type_of(value):
    """C++ type of a record field; anything else fails closed."""
    if type(value) is bool:
        return "bool"
    if type(value) is int:
        return UINT32
    if type(value) is float:
        return "float"
    if type(value) is str:
        return "char[]"
    if type(value) is tuple:
        return UINT32 + "[]"
    raise ValueError("hud_contract_value_unsupported")


def _record(prefix, record):
    return [(f"k{prefix}{_camel(field.name)}", _type_of(getattr(record, field.name)), getattr(record, field.name))
            for field in fields(record)]


def _layout(prefix, layout):
    """Byte offset of each little-endian field, then the layout's total size."""
    entries, codes = [], "<"
    for name, code in layout:
        entries.append((f"k{prefix}{_camel(name)}Offset", UINT32, struct.calcsize(codes)))
        codes += code
    return entries + [(f"k{prefix}Bytes", UINT32, struct.calcsize(codes))]


def _sections():
    magic_field = dict(contract.PACKET_HEADER_FIELDS)["magic"]
    if struct.calcsize("<" + magic_field) != len(contract.PACKET_MAGIC):
        raise ValueError("hud_contract_packet_magic_size")
    panel_limits = [(f"kPanel{_camel(name)}{bound}", "float", float(value))
                    for name, low, high in overlay.PANEL_LIMITS for bound, value in (("Min", low), ("Max", high))]
    return (
        ("HudConfig: sightcircuit.hud.contract.HUD_CONFIG",
         _record("Hud", contract.HUD_CONFIG) +
         [("kHudConfigDigest", "char[]", contract.config_digest(contract.HUD_CONFIG))]),
        ("Calibration marker: sightcircuit.hud.contract.MARKER", _record("Marker", contract.MARKER)),
        ("Pipe packets: sightcircuit.hud.contract layouts and opcodes",
         [("kPacketMagic", "char[]", contract.PACKET_MAGIC.decode("ascii"))] +
         _layout("PacketHeader", contract.PACKET_HEADER_FIELDS) +
         _layout("Settings", contract.SETTINGS_FIELDS) +
         _layout("FramePrefix", contract.FRAME_PREFIX_FIELDS) +
         _layout("ExpiringFramePrefix", contract.EXPIRING_FRAME_PREFIX_FIELDS) +
         _layout("Visibility", contract.VISIBILITY_FIELDS) +
         [("kOpcodeFrame", UINT32, contract.OPCODE_FRAME), ("kOpcodeSettings", UINT32, contract.OPCODE_SETTINGS),
          ("kOpcodeStop", UINT32, contract.OPCODE_STOP),
          ("kOpcodeExpiringFrame", UINT32, contract.OPCODE_EXPIRING_FRAME),
          ("kOpcodeVisibility", UINT32, contract.OPCODE_VISIBILITY)]),
        ("Limits: sightcircuit.hud.contract",
         [("kMarkerMinSeconds", "int", contract.MARKER_MIN_SECONDS),
          ("kMarkerMaxSeconds", "int", contract.MARKER_MAX_SECONDS),
          ("kMaxDisplayAgeNs", "std::uint64_t", contract.MAX_DISPLAY_AGE_NS),
          ("kMaxSide", UINT32, contract.MAX_SIDE), ("kRgbaBytes", UINT32, contract.RGBA_BYTES),
          ("kBridgeConnectBudgetSeconds", UINT32, contract.BRIDGE_CONNECT_BUDGET_SECONDS),
          ("kVisibilityEventBoundNs", "std::uint64_t", contract.VISIBILITY_EVENT_BOUND_NS)]),
        ("Panel limits and defaults: sightcircuit.overlay.PANEL_LIMITS and PanelSettings",
         panel_limits + _record("PanelDefault", overlay.PanelSettings())),
    )


def _literal(ctype, value):
    """One C++ initializer; out-of-range or unprintable values fail closed."""
    return native_header.literal(ctype, value, UNSUPPORTED)


def _declaration(name, ctype, value):
    return native_header.declaration(name, ctype, value, UNSUPPORTED)


def _entries():
    return native_header.entries_of(_sections(), DUPLICATED)


def contract_digest():
    """SHA-256 of every generated name, type and value."""
    return native_header.digest_of(_entries())


def header_text():
    return native_header.render(BANNER, NAMESPACE, _sections(),
                                "SHA-256 of every value above; --render-calibration-marker reports it.",
                                unsupported=UNSUPPORTED, duplicated=DUPLICATED)


def check(path=HEADER):
    """True when ``path`` holds exactly the generated header."""
    return native_header.check(path, header_text())


def write(path=HEADER):
    """Replace ``path`` with the generated header; returns whether it changed."""
    return native_header.write(path, header_text())
